import { chromium } from '/tmp/bittybox-reveal-qa/node_modules/playwright/index.mjs';
import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
const base = process.argv[2] || 'http://127.0.0.1:4178';
const fixtures = JSON.parse(readFileSync('/root/backups/bittybox-reveal/fixtures.json', 'utf8'));
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const checks = [];
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  const errors = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(base + '/', { waitUntil: 'networkidle' });
  assert.ok(await page.locator('#root').innerText());
  checks.push('homepage React mount');
  await page.goto(base + fixtures.credential);
  await page.locator('input').first().fill('00000000');
  await page.getByRole('button', { name: 'UNSEAL TRANSMISSION', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: /incorrect/i }).waitFor();
  assert.equal(await page.locator('iframe').count(), 0);
  assert.equal(await page.locator('[data-ceremony-reveal]').count(), 0);
  checks.push('wrong passcode stays sealed, no reveal/iframe');
  await page.screenshot({ path: '/root/backups/bittybox-reveal/gate-mobile.png' });
  await page.locator('input').first().fill('12345678');
  await page.getByRole('button', { name: 'UNSEAL TRANSMISSION', exact: true }).click();
  await page.locator('[data-ceremony-reveal="vault-door"]').waitFor({ timeout: 5000 });
  assert.equal(await page.locator('iframe').count(), 0);
  await page.screenshot({ path: '/root/backups/bittybox-reveal/reveal-mobile.png' });
  await page.frameLocator('iframe').getByRole('heading', { name: 'REVEAL VERIFIED', exact: true }).waitFor();
  checks.push('correct passcode → vault-door → verified content');
  await page.evaluate(url => { location.hash = new URL(url, location.origin).hash; }, fixtures.tap);
  await page.getByRole('button', { name: 'TAP TO UNSEAL', exact: true }).waitFor();
  assert.equal(await page.locator('iframe').count(), 0);
  await page.getByRole('button', { name: 'TAP TO UNSEAL', exact: true }).click();
  await page.getByRole('button', { name: 'UNSEAL TRANSMISSION', exact: true }).click();
  await page.frameLocator('iframe').getByRole('heading', { name: 'REVEAL VERIFIED', exact: true }).waitFor();
  checks.push('same-tab hash navigation relocks; tap gesture opens');
  await page.goto(base + fixtures.corrupt);
  await page.getByRole('alert').filter({ hasText: 'INVALID CEREMONY' }).waitFor();
  assert.equal(await page.locator('iframe').count(), 0);
  checks.push('corrupt ceremony blocked visibly');
  await page.goto(base + fixtures.noLock);
  await page.frameLocator('iframe').getByRole('heading', { name: 'REVEAL VERIFIED', exact: true }).waitFor();
  checks.push('unlocked URL still renders');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto(base + fixtures.credential);
  await page.locator('input').first().fill('12345678');
  await page.getByRole('button', { name: 'UNSEAL TRANSMISSION', exact: true }).click();
  await page.frameLocator('iframe').getByRole('heading', { name: 'REVEAL VERIFIED', exact: true }).waitFor();
  assert.equal(await page.locator('[data-ceremony-reveal]').count(), 0);
  checks.push('reduced-motion completion');
  assert.deepEqual(errors, []);
  checks.push('no uncaught page errors');
  console.log(JSON.stringify({ base, passed: true, checks }, null, 2));
  writeFileSync('/root/backups/bittybox-reveal/' + (base.startsWith('https') ? 'live' : 'preview') + '-verification.json', JSON.stringify({ base, passed: true, checks }, null, 2));
} catch (error) {
  console.error('FAILED after:', checks, error);
  process.exitCode = 1;
} finally { await browser.close(); }
